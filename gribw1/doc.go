// gribw1 是 GRIB edition 1 的**写入**器（grib1 包的逆操作、gribw 包的兄弟）。
//
// 为什么独立成包而不是并进 gribw：GRIB2 writer 是「模板 + spec.Walk」驱动的
// （section 3/4/5/7 各有模板描述符），而 GRIB1 是**定长字节布局 + 五种段**，
// 没有模板概念，两套装配逻辑几乎没有可共享的中间层。强行合在一起只会让两个
// 版本的分支条件互相污染。放进 grib1 包也不行 —— 那边是纯解码、只读语义干净。
//
// 覆盖范围（与 grib1 解码器对称）：
//   - 段 0 IS / 段 1 PDS / 段 2 GDS / 段 3 BMS（可选）/ 段 4 BDS / '7777'
//   - 数据：简单打包（全位宽 0..32），公式 Y = (R + X·2^E)·10^(−D)
//   - 网格：类型 0（规则经纬）、类型 4（高斯）；其余类型 fail-loud
//   - 层：单层（2 字节）与层组（两个 1 字节）两种 PDS 布局
//
// 不覆盖：GRIB1 的二阶打包 / 球谐 / IEEE 数据段（与 grib1 解码器一致），
// 无 GDS 的预定义网格。要那些得一寸一寸加，不加就不写错字节。
