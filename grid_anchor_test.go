// gridAnchor is one sampled point of the golden C38/T30 grid. The values were
// recorded on amd64 and verified against the eccodes replay (max |Δ| ≈ 1e-13°).
// They make the cross-architecture contract explicit: a platform whose packed
// digest is not anchored must reproduce these samples within
// gridAnchorTolerance, while the byte-exact digest stays a hard gate on the
// platforms whose digest pair is recorded.
type gridAnchor struct {
	Index int
	Lat   float64
	Lon   float64
}

// gridAnchorTolerance is the cross-architecture coordinate tolerance. Observed
// ulp drift between amd64, darwin/arm64 and wasm is ~1e-13 degrees, leaving six
// orders of magnitude of headroom while still catching formula or scan-order
// regressions.
const gridAnchorTolerance = 1e-9

// checkGridDigests enforces the packed-float64 anchors. On a platform whose
// digest pair is recorded the digests must match bit for bit; anywhere else
// (wasm, other GOARCH values, other GOAMD64 variants) the digest is not
// portable, so the sampled anchors are checked with gridAnchorTolerance and
// the observed digest is logged for future anchoring.
func checkGridDigests(t *testing.T, lats, lons []float64, latsDigest, lonsDigest string) {
	t.Helper()
	if len(lats) != len(lons) {
		t.Fatalf("lats/lons length = %d/%d", len(lats), len(lons))
	}
	if knownLatsDigest(latsDigest) && knownLonsDigest(lonsDigest) {
		return
	}
	for _, a := range c38GridAnchors {
		if a.Index >= len(lats) {
			t.Fatalf("anchor index %d out of range %d", a.Index, len(lats))
		}
		if d := math.Abs(lats[a.Index] - a.Lat); d > gridAnchorTolerance {
			t.Errorf("lat[%d] = %.17g, want %.17g (Δ=%g > %g)", a.Index, lats[a.Index], a.Lat, d, gridAnchorTolerance)
		}
		if d := lonDistance(lons[a.Index], a.Lon); d > gridAnchorTolerance {
			t.Errorf("lon[%d] = %.17g, want %.17g (Δ=%g > %g)", a.Index, lons[a.Index], a.Lon, d, gridAnchorTolerance)
		}
	}
	t.Logf("digests lats=%s lons=%s are not anchored on this platform; %d sampled points match within %g degrees",
		latsDigest, lonsDigest, len(c38GridAnchors), gridAnchorTolerance)
}

// lonDistance returns the smaller angular distance so 359.999… and 0.000…
// representations of the same meridian do not count as a mismatch.
func lonDistance(a, b float64) float64 {
	d := math.Abs(a - b)
	if d > 180 {
		d = 360 - d
	}
	return d
}

