// 命令 specgen 从 specdata/ 里内置的 WMO CSV 文件生成 simple-grib 的
// Go 规范数据。
//
// 输入（specdata/）：
//   - GRIB2_Template_<S>_<N>_..._en.csv      （254 个模板定义）
//   - GRIB2_CodeFlag_<S>_<N>(_<X>_<Y>)_..._en.csv  （175 个代码/标志表）
//   - CCT/C11.csv                            （通用代码表 C-11，中心）
//   - PROVENANCE.txt                         （来源仓库 / 提交 / 修订级别）
//
// 输出（spec/）：
// - doc.go 版本常量（provenance 戳）
// - tables_gen.go 全部代码/标志表 + 全部模板字段描述符 + 统计模板的区间收尾偏移
//
// 代码/标志表顺带解析 UnitComments_en 列（如果该 CSV 有列）：它给出表内每个
// 代码的单位（如 K、Pa、m）。没有该列、空白、"-" 或指向别的表
// （"Code table 4.253"）都归一成空单位 —— 它们是"无量纲/单位别处定义"，
// 不是单位。
//
// 另外识别模板里的 "Year [of|time of] end of overall time interval" 字段
// （WMO 统计模板 4.8–4.14），把它的基于 0 的 section 偏移写进
// genEndIntervalOffsets：WMO 把统计区间放在两个地方 —— 4.4 时间字段是
// "区间起点"，而 end-of-interval 时间戳是"区间终点"。两者都是解析
// ecCodes 兼容 forecastTime/step/validityDate 语义的必要输入。
//
// 该生成器「失败即报错」：任何它无法确定性分类的 CSV 行都会带着
// 文件+行号上下文中止构建。它绝不猜测。
package main

import (
	"bufio"
	"bytes"
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func main() {
	dir := flag.String("dir", "specdata", "directory with vendored WMO CSVs")
	out := flag.String("out", "spec", "output directory for generated Go files")
	checkOnly := flag.Bool("check", false, "verify generated files are in sync; do not write")
	flag.Parse()

	prov, err := readProvenance(*dir)
	if err != nil {
		fatal("provenance: %v", err)
	}

	tables, err := genTables(*dir)
	if err != nil {
		fatal("tables: %v", err)
	}
	templates, err := genTemplates(*dir)
	if err != nil {
		fatal("templates: %v", err)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by cmd/specgen from specdata/ (%s).\n// DO NOT EDIT.\n\npackage spec\n\n", prov.summary())
	buf.WriteString(tables.goSource())
	buf.WriteString(templates.goSource())
	tablesGen, gerr := goformat(buf.String())
	if gerr != nil {
		fatal("tables: gofmt: %v", gerr)
	}

	// doc.go 的包/常量文档是手写的双语文本，但由本生成器持有：否则任何人
	// 跑一次 go generate 就会把它们从磁盘上抹掉。变更文本请改这里。
	// doc.go's package doc is hand-written prose, owned by this generator so
	// that running "go generate" never deletes it from disk. Edit it here.
	docSrc := "// Code generated by cmd/specgen. DO NOT EDIT.\n\n" +
		"// Package spec 提供 WMO GRIB2 规范数据的只读访问：代码表（表 4.1 参数类别、\n" +
		"// 表 4.2.<discipline>.<category> 参数、CCT-11 中心等）与模板字段描述符由\n" +
		"// cmd/specgen 从 specdata/ 源数据生成；包内提供按表 id 查表、按代码区间匹配\n" +
		"// 以及参数三元组命名的接口。\n" +
		"//\n" +
		"// Package spec provides read-only access to WMO GRIB2 specification data:\n" +
		"// code tables (table 4.1 parameter categories, table 4.2.<discipline>.<category>\n" +
		"// parameters, CCT-11 centres, …) and template field descriptors are generated\n" +
		"// from the specdata/ sources by cmd/specgen; the package exposes lookups by\n" +
		"// table id, range matching of codes, and parameter naming from a\n" +
		"// discipline/category/number triple.\n" +
		"package spec\n\n" +
		"// Version 标识本包内嵌的 WMO 规范数据来源：上游 GRIB2 与 Common Code Tables\n" +
		"// 仓库的提交号、修订截止日期、同步时间与同步方式；刷新步骤见 specdata/README.md。\n" +
		"//\n" +
		"// Version identifies the WMO specification data baked into this package: the\n" +
		"// upstream GRIB2 and Common Code Tables commit hashes, the amendment cutoff,\n" +
		"// the sync date and the sync method; the refresh procedure is documented in\n" +
		"// specdata/README.md.\n" +
		fmt.Sprintf("const Version = %q\n", prov.summary())
	doc, err := goformat(docSrc)
	if err != nil {
		fatal("doc: gofmt: %v", err)
	}

	if *checkOnly {
		for name, content := range map[string]string{
			filepath.Join(*out, "tables_gen.go"): tablesGen,
			filepath.Join(*out, "doc.go"):        doc,
		} {
			cur, err := os.ReadFile(name)
			if err != nil {
				fatal("check: %v (run: go generate ./spec)", err)
			}
			if !bytes.Equal(cur, []byte(content)) {
				fatal("check: %s is out of date with specdata/ (run: go generate ./spec)", name)
			}
		}
		fmt.Println("specgen -check: generated files in sync")
		return
	}

	if err := os.MkdirAll(*out, 0o755); err != nil {
		fatal("%v", err)
	}
	if err := os.WriteFile(filepath.Join(*out, "tables_gen.go"), []byte(tablesGen), 0o644); err != nil {
		fatal("%v", err)
	}
	if err := os.WriteFile(filepath.Join(*out, "doc.go"), []byte(doc), 0o644); err != nil {
		fatal("%v", err)
	}
	fmt.Printf("specgen: wrote %s/tables_gen.go (%d tables), %s/doc.go\n", *out, len(tables.tables), *out)
	fmt.Printf("specgen: %d templates, %d fields; symbolic-field templates: %d (see list below)\n",
		len(templates.templates), templates.totalFields, len(templates.symbolicList))
	for _, t := range templates.symbolicList {
		fmt.Printf("  - template %s: %s\n", t.id, t.name)
	}
}

func fatal(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "specgen: "+format+"\n", a...)
	os.Exit(1)
}

// goformat runs generated source through go/format so the committed files are
// always gofmt-clean and specgen -check stays a stable, diffable comparison.
// Without it the generator's raw struct renderings drift from gofmt's shape.
func goformat(src string) (string, error) {
	out, err := format.Source([]byte(src))
	if err != nil {
		return "", err
	}
	return string(out), nil
}

// ---------------------------------------------------------------- 出处（provenance）

type provenance struct{ lines []string }

func (p provenance) summary() string { return strings.Join(p.lines, "; ") }

func readProvenance(dir string) (provenance, error) {
	b, err := os.ReadFile(filepath.Join(dir, "PROVENANCE.txt"))
	if err != nil {
		return provenance{}, fmt.Errorf("missing PROVENANCE.txt in %s: %w", dir, err)
	}
	var p provenance
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		p.lines = append(p.lines, line)
	}
	if len(p.lines) == 0 {
		return provenance{}, fmt.Errorf("PROVENANCE.txt in %s is empty", dir)
	}
	return p, nil
}

// ------------------------------------------------------------------- 代码/标志表

type tableEntry struct {
	min, max int32
	name     string
	status   string
	unit     string
}

type gribTable struct {
	id      string // "4.1"、"4.2.0.13"、"CCT-11"
	title   string
	entries []tableEntry
}

type tableSet struct {
	tables []*gribTable
}

func (t *tableSet) goSource() string {
	var b bytes.Buffer
	b.WriteString("\n// ---- generated code tables -------------------------------------------\n\n")
	b.WriteString("type genEntry struct{ min, max int32; name, status, unit string }\n\n")
	b.WriteString("type genTable struct{ id, title string; entries []genEntry }\n\n")
	b.WriteString("var genTables = []*genTable{\n")
	for _, t := range t.tables {
		fmt.Fprintf(&b, "\t{id: %s, title: %s, entries: []genEntry{\n",
			strconv.Quote(t.id), strconv.Quote(t.title))
		for _, e := range t.entries {
			fmt.Fprintf(&b, "\t\t{%d, %d, %s, %s, %s},\n", e.min, e.max,
				strconv.Quote(e.name), strconv.Quote(e.status), strconv.Quote(e.unit))
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n")
	return b.String()
}

// unitPlaceholderRe 匹配指向别处单位表的注释（如 "Code table 4.253"）——
// 它不是单位，而是"单位定义在别处"的指针。
var unitPlaceholderRe = regexp.MustCompile(`(?i)^code table\b`)

// normalizeUnit 把 UnitComments_en 的原始文本归一成单位字符串。
// 空白、"-"（WMO 的无量纲写法）与指向别表的注释都归一成 ""。
func normalizeUnit(s string) string {
	s = strings.TrimSpace(s)
	if s == "" || s == "-" || unitPlaceholderRe.MatchString(s) {
		return ""
	}
	return s
}

var codeRangeRe = regexp.MustCompile(`^(\d+)(?:-(\d+))?$`)

func genTables(dir string) (*tableSet, error) {
	files, err := filepath.Glob(filepath.Join(dir, "GRIB2_CodeFlag_*.csv"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	set := &tableSet{}
	for _, f := range files {
		id, ok := tableIDFromName(filepath.Base(f))
		if !ok {
			fatal("unrecognized code-flag filename: %s", f)
		}
		t, err := parseCodeFlagFile(f)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", filepath.Base(f), err)
		}
		t.id = id
		set.tables = append(set.tables, t)
	}

	// CCT（通用代码表）—— 格式不同，每个表一个文件。
	ccts, err := parseCCTs(filepath.Join(dir, "CCT"))
	if err != nil {
		return nil, fmt.Errorf("CCT: %w", err)
	}
	set.tables = append(set.tables, ccts...)
	return set, nil
}

// tableIDFromName 把 GRIB2_CodeFlag_4_2_0_13_CodeTable_en.csv 映射成 "4.2.0.13"。
func tableIDFromName(name string) (string, bool) {
	base := strings.TrimSuffix(name, ".csv")
	base = strings.TrimPrefix(base, "GRIB2_CodeFlag_")
	base = strings.TrimSuffix(base, "_CodeTable_en")
	base = strings.TrimSuffix(base, "_FlagTable_en")
	parts := strings.Split(base, "_")
	if len(parts) < 2 || len(parts) > 4 {
		return "", false
	}
	for _, p := range parts {
		if _, err := strconv.Atoi(p); err != nil {
			return "", false
		}
	}
	return strings.Join(parts, "."), true
}

func parseCodeFlagFile(path string) (*gribTable, error) {
	fh, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer fh.Close()
	r := csv.NewReader(fh)
	recs, err := r.ReadAll()
	if err != nil {
		return nil, fmt.Errorf("csv: %w", err)
	}
	if len(recs) < 2 {
		return nil, fmt.Errorf("no data rows")
	}
	hdr := recs[0]
	col := map[string]int{}
	for i, h := range hdr {
		col[strings.TrimSpace(h)] = i
	}
	for _, need := range []string{"CodeFlag", "MeaningParameterDescription_en", "Status"} {
		if _, ok := col[need]; !ok {
			return nil, fmt.Errorf("missing column %q (header: %v)", need, hdr)
		}
	}
	// UnitComments_en 是可选的：CCT 表（C-11/C-14）没有单位列。
	unitCol, hasUnit := col["UnitComments_en"]
	get := func(rec []string, name string) string {
		i := col[name]
		if i < 0 || i >= len(rec) {
			return ""
		}
		return strings.TrimSpace(rec[i])
	}
	getUnit := func(rec []string) string {
		if !hasUnit || unitCol >= len(rec) {
			return ""
		}
		return normalizeUnit(rec[unitCol])
	}
	title := get(recs[1], "Title_en")
	t := &gribTable{title: title}
	for li, rec := range recs[1:] {
		line := li + 2 // 1-based，header = line 1
		codeStr := get(rec, "CodeFlag")
		if codeStr == "" {
			// 交叉引用表：取值委托给外部目录（如 "See Common Code table C-14"）。
			// 发一个哨兵条目（min>max → 永不匹配），带上引用文本。
			t.entries = append(t.entries, tableEntry{
				min:    -1,
				max:    -1,
				name:   get(rec, "MeaningParameterDescription_en"),
				status: get(rec, "Status"),
				unit:   getUnit(rec),
			})
			continue
		}
		m := codeRangeRe.FindStringSubmatch(codeStr)
		if m == nil {
			// 已知的 WMO 数据怪癖："32768-"（开放区间，如 4.243 第 43 行）。
			// 确定性地归一化到完整的 16 位码空间。
			if openRe := regexp.MustCompile(`^(\d+)-$`); openRe.MatchString(codeStr) {
				fmt.Fprintf(os.Stderr, "specgen: warning: %s line %d: open-ended range %q normalized to %s-65535\n",
					filepath.Base(path), line, codeStr, codeStr[:len(codeStr)-1])
				m = []string{codeStr, codeStr[:len(codeStr)-1], "65535"} // [完整串, 下限, 上限]
			}
		}
		if m == nil {
			return nil, fmt.Errorf("line %d: unparseable code range %q", line, codeStr)
		}
		min, _ := strconv.Atoi(m[1])
		max := min
		if m[2] != "" {
			max, _ = strconv.Atoi(m[2])
		}
		t.entries = append(t.entries, tableEntry{
			min:    int32(min),
			max:    int32(max),
			name:   get(rec, "MeaningParameterDescription_en"),
			status: get(rec, "Status"),
			unit:   getUnit(rec),
		})
	}
	return t, nil
}

// parseCCTs 解析所有内置的通用代码表文件（CCT/C<N>.csv）。
// 列布局：CREX2、GRIB2_BUFR4 码、名称、状态。标注行
// （如 "00001-00009: WMCs" 这类区间）没有单一码，会被跳过。
func parseCCTs(dir string) ([]*gribTable, error) {
	files, err := filepath.Glob(filepath.Join(dir, "C*.csv"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	var out []*gribTable
	for _, f := range files {
		base := strings.TrimSuffix(filepath.Base(f), ".csv") // 如 "C11"
		n, err := strconv.Atoi(strings.TrimPrefix(base, "C"))
		if err != nil {
			continue
		}
		t, err := parseCCTFile(f, fmt.Sprintf("CCT-%d", n))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", filepath.Base(f), err)
		}
		out = append(out, t)
	}
	return out, nil
}

func parseCCTFile(path, id string) (*gribTable, error) {
	fh, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer fh.Close()
	r := csv.NewReader(fh)
	recs, err := r.ReadAll()
	if err != nil {
		return nil, fmt.Errorf("csv: %w", err)
	}
	if len(recs) < 2 {
		return nil, fmt.Errorf("no data rows")
	}
	// 两种已知布局；从表头判断。
	codeCol, nameCol := 1, 2 // C-11 风格：CREX2、GRIB2_BUFR4、Name、Status
	if strings.Contains(recs[0][0], "CodeFigure") {
		codeCol, nameCol = 0, 1 // C-14 风格：CodeFigure、Meaning、...
	}
	t := &gribTable{id: id, title: "Common Code Table " + id}
	for _, rec := range recs[1:] {
		if len(rec) <= nameCol {
			continue
		}
		codeStr := strings.TrimSpace(rec[codeCol])
		v, err := strconv.Atoi(strings.TrimLeft(codeStr, "0"))
		if err != nil || v < 0 || v > 65535 {
			continue // 标注行没有单一码
		}
		name := strings.TrimSpace(rec[nameCol])
		status := "Operational"
		for _, c := range rec {
			if strings.EqualFold(strings.TrimSpace(c), "Experimental") {
				status = "Experimental"
			}
		}
		t.entries = append(t.entries, tableEntry{min: int32(v), max: int32(v), name: name, status: status})
	}
	if len(t.entries) == 0 {
		return nil, fmt.Errorf("no entries parsed")
	}
	return t, nil
}

// --------------------------------------------------------------- 模板（templates）

const (
	kindU8 byte = iota
	kindU16
	kindU32
	kindF32
	kindVariable
	kindSymbolic
)

var kindName = map[byte]string{
	kindU8: "U8", kindU16: "U16", kindU32: "U32", kindF32: "F32",
	kindVariable: "Variable", kindSymbolic: "Symbolic",
}

type genField struct {
	start int32 // 基于 0 的 section 偏移；-1 表示无固定起点的符号字段
	count int16 // 0 = 无界（variable）
	kind  byte
	tsec  int16  // 表引用：0=无，255=CCT
	tflag int16  // 标志号（tsec==255 时为 CCT 号）
	expr  string // 符号字段的原始 OctetNo 表达式
}

type genTemplate struct {
	id               string // "3.0"
	name             string
	status           string
	fields           []genField
	endInterval      int32 // "Year…end of overall time interval" 的基于 0 偏移；-1 = 无或参数化
	endIntervalField bool  // 模板是否带 end-of-interval 时间戳（位置固定或参数化）
	statProcess      int32 // "Statistical process…"（表 4.7）的基于 0 偏移；-1 = 无
	probType         int32 // "Probability type"（表 4.9）的基于 0 偏移；-1 = 无
}

// endIntervalYearRe 匹配统计模板里的区间终点年份行。4.8 的写法是
// "Year - time of end of overall time interval"，4.9–4.14 是
// "Year of end of overall time interval"；要求锚定在 Year 上，避免命中
// 相邻的 month/day/hour 行，也避免命中 "time of beginning of overall
// time interval"（那 个子串不同）。
var endIntervalYearRe = regexp.MustCompile(`(?i)^year\b.*\bend of overall time interval\b`)

// statProcessRe 匹配统计模板的第一个 "Statistical process used to
// calculate the processed field…" 行（表 4.7 的 typeOfStatisticalProcessing，
// WMO CSV 把它的 codeTable 误标成 4.1，因此按内容锚定而不是按表引用）。
// 多重时间范围的模板从外到内嵌套，第一个即 ecCodes 的
// typeOfStatisticalProcessing 键所指的那一层。
var statProcessRe = regexp.MustCompile(`(?i)^statistical process\b`)

// probTypeRe 匹配概率模板（4.5/4.9 及其派生）的 "Probability type" 字段
// （表 4.9）。该字段之后的布局在所有含概率字段的模板里一致：
// +1 起为 lower limit 的 scale factor(1B)+scaled value(4B)，+6 起为
// upper limit 同构——据此 Product 只需一个偏移就能读出全部概率限值。
var probTypeRe = regexp.MustCompile(`(?i)^probability type\b`)

func (t *genTemplate) hasSymbolic() bool {
	for _, f := range t.fields {
		if f.kind == kindSymbolic {
			return true
		}
	}
	return false
}

type templateSet struct {
	templates    []*genTemplate
	totalFields  int
	symbolicList []*genTemplate
}

func (t *templateSet) goSource() string {
	var b bytes.Buffer
	b.WriteString("\n// ---- generated template descriptors ----------------------------------\n\n")
	b.WriteString("const (\n\tkindU8 byte = iota\n\tkindU16\n\tkindU32\n\tkindF32\n\tkindVariable\n\tkindSymbolic\n)\n\n")
	b.WriteString("type genField struct{ start int32; count int16; kind byte; tsec, tflag int16; expr string }\n\n")
	b.WriteString("type genTemplate struct{ id, name, status string; fields []genField }\n\n")
	b.WriteString("var genTemplates = []*genTemplate{\n")
	for _, t := range t.templates {
		fmt.Fprintf(&b, "\t{id: %s, name: %s, status: %s, fields: []genField{\n",
			strconv.Quote(t.id), strconv.Quote(t.name), strconv.Quote(t.status))
		for _, f := range t.fields {
			fmt.Fprintf(&b, "\t\t{%d, %d, kind%s, %d, %d, %s},\n",
				f.start, f.count, kindName[f.kind], f.tsec, f.tflag, strconv.Quote(f.expr))
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n\n")
	// 统计模板（4.8–4.14）的 "time of end of overall time interval" 年份字段
	// 偏移。key 是模板 id，value 是 section 字节里基于 0 的偏移；-1 表示字段
	// 存在但位置参数化（位于重复块内），解析侧不得猜偏移。
	b.WriteString("// genEndIntervalOffsets maps product template id -> 0-based section\n")
	b.WriteString("// offset of the Year field of the \"time of end of overall time interval\"\n")
	b.WriteString("// timestamp (WMO statistical templates 4.8-4.14). -1 means the field\n")
	b.WriteString("// exists but sits at a parametrized position; readers must not guess.\n")
	b.WriteString("var genEndIntervalOffsets = map[string]int32{\n")
	for _, t := range t.templates {
		if t.endInterval == -1 && t.hasEndIntervalField() {
			fmt.Fprintf(&b, "\t%s: -1, // parametrized position\n", strconv.Quote(t.id))
		}
	}
	for _, t := range t.templates {
		if t.endInterval >= 0 {
			fmt.Fprintf(&b, "\t%s: %d,\n", strconv.Quote(t.id), t.endInterval)
		}
	}
	b.WriteString("}\n\n")
	// 统计模板的 typeOfStatisticalProcessing（表 4.7）字段偏移；-1 = 无或参数化。
	b.WriteString("// genStatProcessOffsets maps product template id -> 0-based section\n")
	b.WriteString("// offset of the first (outermost) \"Statistical process\" field (table 4.7\n")
	b.WriteString("// typeOfStatisticalProcessing) of the WMO statistical templates.\n")
	b.WriteString("var genStatProcessOffsets = map[string]int32{\n")
	for _, t := range t.templates {
		if t.statProcess >= 0 {
			fmt.Fprintf(&b, "\t%s: %d,\n", strconv.Quote(t.id), t.statProcess)
		}
	}
	b.WriteString("}\n\n")
	// 概率模板（4.5/4.9 及派生）的 "Probability type" 字段偏移；其后 +1/+2
	// 为 lower limit 的 scale factor/scaled value，+6/+7 为 upper limit。
	b.WriteString("// genProbTypeOffsets maps product template id -> 0-based section\n")
	b.WriteString("// offset of the \"Probability type\" field (table 4.9). The lower limit\n")
	b.WriteString("// scale factor / scaled value follow at +1/+2 and the upper limit at\n")
	b.WriteString("// +6/+7. -1 means the field sits at a parametrized position.\n")
	b.WriteString("var genProbTypeOffsets = map[string]int32{\n")
	for _, t := range t.templates {
		if t.probType >= 0 {
			fmt.Fprintf(&b, "\t%s: %d,\n", strconv.Quote(t.id), t.probType)
		}
	}
	b.WriteString("}\n")
	return b.String()
}

// hasEndIntervalField reports whether the template carries an
// "…end of overall time interval" timestamp at all (fixed or parametrized).
func (t *genTemplate) hasEndIntervalField() bool { return t.endIntervalField }

var (
	plainStartRe = regexp.MustCompile(`^(\d+)$`)
	plainRangeRe = regexp.MustCompile(`^(\d+)-(\d+)$`)
	varLenRe     = regexp.MustCompile(`^(\d+)-([a-z][a-z0-9_]*)$`) // "6-nn"、"49-ii"
	sameAsRe     = regexp.MustCompile(`^Same as .*?template (\d+\.\d+)$`)
)

func genTemplates(dir string) (*templateSet, error) {
	files, err := filepath.Glob(filepath.Join(dir, "GRIB2_Template_*.csv"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	set := &templateSet{}
	for _, f := range files {
		id, ok := templateIDFromName(filepath.Base(f))
		if !ok {
			fatal("unrecognized template filename: %s", f)
		}
		t, err := parseTemplateFile(f)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", filepath.Base(f), err)
		}
		t.id = id
		// 变长放置规则：第一个 Variable 字段之后，任何字段都不能带固定起点
		// （既覆盖「变长放最后」，也覆盖像 3.4 那种经度-纬度的连续列表）。
		seenVar := false
		for i, fld := range t.fields {
			if fld.kind == kindVariable {
				seenVar = true
				continue
			}
			if seenVar && fld.start >= 0 {
				return nil, fmt.Errorf("template %s: field at position %d has a fixed start after a variable-length field", id, i)
			}
		}
		set.templates = append(set.templates, t)
	}

	// 把 "Same as template S.N" 引用行展开成被引用模板的固定字段，
	// 前提是区间完全吻合。会一直跑到不动点，因为引用可能嵌套（5.3 -> 5.2 -> 5.0）。
	byID := map[string]*genTemplate{}
	for _, t := range set.templates {
		byID[t.id] = t
	}
	for changed := true; changed; {
		changed = false
		for _, t := range set.templates {
			for i := range t.fields {
				f := &t.fields[i]
				if !strings.HasPrefix(f.expr, "sameas:") || strings.Contains(f.expr, "(not expanded") || f.start < 0 || f.count == 0 {
					continue // 不可展开：符号/变长区间，或已标记过
				}
				srcID := strings.TrimPrefix(f.expr, "sameas:")
				src, ok := byID[srcID]
				if !ok {
					return nil, fmt.Errorf("template %s: reference to unknown template %s", t.id, srcID)
				}
				var fixed []genField
				for _, sf := range src.fields {
					if sf.kind == kindVariable {
						continue // 被引用模板自己声明尾部
					}
					fixed = append(fixed, sf)
				}
				if len(fixed) == 0 {
					return nil, fmt.Errorf("template %s: referenced template %s has no fixed fields", t.id, srcID)
				}
				first, last := fixed[0], fixed[len(fixed)-1]
				end := int(last.start) + int(last.count) - 1
				if first.start != f.start || end != int(f.start)+int(f.count)-1 {
					f.expr = "sameas:" + srcID + " (not expanded: span mismatch)"
					continue // 保留为 Symbolic 标记；确定性的，不会死循环
				}
				t.fields = append(t.fields[:i], append(fixed, t.fields[i+1:]...)...)
				changed = true
				break // 重新开始扫描该模板的字段
			}
		}
	}
	for _, t := range set.templates {
		set.totalFields += len(t.fields)
		if t.hasSymbolic() {
			set.symbolicList = append(set.symbolicList, t)
		}
	}
	return set, nil
}

func templateIDFromName(name string) (string, bool) {
	base := strings.TrimSuffix(name, ".csv")
	base = strings.TrimPrefix(base, "GRIB2_Template_")
	parts := strings.SplitN(base, "_", 3)
	if len(parts) < 2 {
		return "", false
	}
	for _, p := range parts[:2] {
		if _, err := strconv.Atoi(p); err != nil {
			return "", false
		}
	}
	return parts[0] + "." + parts[1], true
}

func parseTemplateFile(path string) (*genTemplate, error) {
	fh, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer fh.Close()
	r := csv.NewReader(fh)
	recs, err := r.ReadAll()
	if err != nil {
		return nil, fmt.Errorf("csv: %w", err)
	}
	if len(recs) < 2 {
		return nil, fmt.Errorf("no data rows")
	}
	hdr := recs[0]
	col := map[string]int{}
	for i, h := range hdr {
		col[strings.TrimSpace(h)] = i
	}
	for _, need := range []string{"OctetNo", "Contents_en"} {
		if _, ok := col[need]; !ok {
			return nil, fmt.Errorf("missing column %q (header: %v)", need, hdr)
		}
	}
	get := func(rec []string, name string) string {
		i := col[name]
		if i < 0 || i >= len(rec) {
			return ""
		}
		return strings.TrimSpace(rec[i])
	}
	t := &genTemplate{name: get(recs[1], "Title_en"), status: get(recs[1], "Status"), endInterval: -1, statProcess: -1, probType: -1}
	var fixedHits, symbolicHits []int32
	for li, rec := range recs[1:] {
		line := li + 2
		octetNo := get(rec, "OctetNo")
		countStr := get(rec, "OctetCount")
		contents := get(rec, "Contents_en")
		fieldStart := int32(-1)

		fld := genField{}
		switch {
		case sameAsRe.MatchString(contents):
			// "Same as <kind> template S.N" 引用行；当被引用的区间完全吻合时，
			// 在后续一趟中展开。
			fld.kind = kindSymbolic
			fld.expr = "sameas:" + sameAsRe.FindStringSubmatch(contents)[1]
			if m := plainRangeRe.FindStringSubmatch(octetNo); m != nil {
				a, _ := strconv.Atoi(m[1])
				bb, _ := strconv.Atoi(m[2])
				fld.start = int32(a) - 1
				fld.count = int16(bb - a + 1)
			} else {
				fld.start = -1 // "15-nn" / 符号区间：不可展开
			}
		case strings.HasPrefix(contents, "As octets") || strings.Contains(contents, "next innermost step"):
			fld.kind = kindSymbolic // 重复块实例（参数化重复）
			fld.start = -1
			fld.expr = contents
		case octetNo == "":
			fld.kind = kindSymbolic // 描述性/条件行；无固定位置
			fld.start = -1
		default:
			if m := plainStartRe.FindStringSubmatch(octetNo); m != nil {
				start, _ := strconv.Atoi(m[1])
				fld.start = int32(start) - 1 // section 字节中基于 0 的偏移
				fieldStart = fld.start
				count, err := fieldCount(countStr, 1, line, path)
				if err != nil {
					return nil, err
				}
				fld.count = count
				fld.kind = kindForWidth(count, contents, path, line)
			} else if m := plainRangeRe.FindStringSubmatch(octetNo); m != nil {
				a, _ := strconv.Atoi(m[1])
				bb, _ := strconv.Atoi(m[2])
				if countStr != "" {
					c, cerr := strconv.Atoi(countStr)
					switch {
					case cerr != nil:
						return nil, fmt.Errorf("line %d: unparseable OctetCount %q", line, countStr)
					case c > 0 && a+c-1 != bb:
						// WMO 数据怪癖：区间文本与显式 OctetCount 不一致
						//（4.142 "40-4"+2；4.146 "31-32"+4）。相信显式计数 ——
						// 它由相邻字段固定 —— 并告警以供审计。
						fmt.Fprintf(os.Stderr, "specgen: warning: %s line %d: range %q disagrees with OctetCount=%d; using %d-%d\n",
							filepath.Base(path), line, octetNo, c, a, a+c-1)
						bb = a + c - 1
					}
				} else if bb < a {
					return nil, fmt.Errorf("line %d: inverted octet range %q without OctetCount", line, octetNo)
				}
				fld.start = int32(a) - 1
				fieldStart = fld.start
				fld.count = int16(bb - a + 1)
				fld.kind = kindForWidth(fld.count, contents, path, line)
			} else if m := varLenRe.FindStringSubmatch(octetNo); m != nil {
				start, _ := strconv.Atoi(m[1])
				fld.start = int32(start) - 1
				fld.count = 0
				fld.kind = kindVariable
			} else {
				fld.kind = kindSymbolic // 参数化表达式，如 "47+(nt-1)*12"
				fld.start = -1
				fld.expr = octetNo
			}
		}

		// 统计模板的区间终点时间戳。固定位置的（4.8–4.14）记录偏移；位置参数化
		// 的（如 4.114 的 "60+(NUTAFTAC-1)"，位于重复块内）记为 -1：确认字段
		// 存在、但没有可静态绑定的偏移，解析侧因此返回 not-ok 而不是猜一个。
		// 两者同时出现说明上游数据自相矛盾，直接报错。
		if endIntervalYearRe.MatchString(contents) {
			if fieldStart >= 0 {
				fixedHits = append(fixedHits, fieldStart)
			} else {
				symbolicHits = append(symbolicHits, -1)
			}
		}
		if statProcessRe.MatchString(contents) && fieldStart >= 0 && t.statProcess < 0 {
			t.statProcess = fieldStart // 只取第一个（最外层时间范围）
		}
		if probTypeRe.MatchString(contents) {
			if fieldStart >= 0 {
				if t.probType >= 0 {
					return nil, fmt.Errorf("%s line %d: second fixed \"Probability type\" field", path, line)
				}
				t.probType = fieldStart
			} else {
				t.probType = -2 // 存在但位置参数化：不生成偏移，也不报错
				fmt.Fprintf(os.Stderr, "specgen: note: %s line %d: \"Probability type\" at a parametrized position; ProbTypeOffset will return not-ok\n",
					filepath.Base(path), line)
			}
		}

		// 表引用（codeTable 或 flagTable 列）。
		ref := get(rec, "codeTable")
		if ref == "" {
			ref = get(rec, "flagTable")
		}
		if ref != "" {
			switch {
			case strings.EqualFold(ref, "c-11"), strings.EqualFold(ref, "CCT-11"):
				fld.tsec, fld.tflag = 255, 11
			case strings.EqualFold(ref, "c-14"), strings.EqualFold(ref, "CCT-14"):
				fld.tsec, fld.tflag = 255, 14
			default:
				parts := strings.SplitN(ref, ".", 2)
				if len(parts) != 2 {
					return nil, fmt.Errorf("line %d: unparseable table reference %q", line, ref)
				}
				s, err1 := strconv.Atoi(parts[0])
				n, err2 := strconv.Atoi(parts[1])
				if err1 != nil || err2 != nil {
					// 符号表引用（如 4.53/4.54 里的 "4.PTN" 分区表）。
					// 保留原始引用供后用；无法做数值绑定。
					fmt.Fprintf(os.Stderr, "specgen: warning: %s line %d: symbolic table reference %q kept as-is\n",
						filepath.Base(path), line, ref)
					fld.expr = "tabref:" + ref
				} else {
					fld.tsec, fld.tflag = int16(s), int16(n)
				}
			}
		}
		t.fields = append(t.fields, fld)
	}
	switch {
	case len(fixedHits) == 1 && len(symbolicHits) == 0:
		t.endInterval = fixedHits[0]
		t.endIntervalField = true
	case len(fixedHits) == 0 && len(symbolicHits) == 1:
		t.endInterval = -1 // 存在但位置参数化，Offset() 将返回 not-ok
		t.endIntervalField = true
	case len(fixedHits) == 0 && len(symbolicHits) == 0:
		t.endInterval = -1
	default:
		return nil, fmt.Errorf("%s: %d fixed and %d symbolic \"end of overall time interval\" year fields, want exactly 0 or 1",
			path, len(fixedHits), len(symbolicHits))
	}
	if len(symbolicHits) == 1 {
		fmt.Fprintf(os.Stderr, "specgen: note: %s: \"end of overall time interval\" is at a parametrized position; spec.EndIntervalOffset will return not-ok\n",
			filepath.Base(path))
	}
	return t, nil
}

// fieldCount 解析单起点字段的 octet 计数。
func fieldCount(countStr string, def int, line int, path string) (int16, error) {
	if countStr == "" {
		return int16(def), nil
	}
	c, err := strconv.Atoi(countStr)
	if err != nil || c <= 0 {
		return 0, fmt.Errorf("line %d: unparseable OctetCount %q", line, countStr)
	}
	return int16(c), nil
}

// kindForWidth 按宽度和 WMO 内容文本给固定宽度字段分类。
// 非 1/2/4 的宽度（如模板 3.101 的 3 字节本地字段，或 8 字节谱域尺寸）
// 标记为 Symbolic 并告警：它们退化为原始字节访问，而不是阻断生成。
func kindForWidth(count int16, contents, path string, line int) byte {
	switch count {
	case 1:
		return kindU8
	case 2:
		return kindU16
	case 4:
		if strings.Contains(strings.ToLower(contents), "ieee 32-bit floating-point") {
			return kindF32
		}
		return kindU32
	default:
		fmt.Fprintf(os.Stderr, "specgen: warning: %s line %d: field width %d (%q) marked Symbolic\n",
			filepath.Base(path), line, count, contents)
		return kindSymbolic
	}
}

